function fill(tpl, rng) {
  return tpl.replace('{p}', () => pick(rng, PRODUCTS)).replace('{n}', () => pick(rng, QTY));
}

function generate(n = 500, seed = 42) {
  const rng = makeRng(seed);
  const perClass = Math.max(20, Math.floor(n / Object.keys(BANK).length));
  const seen = new Set();
  const rows = [];
  for (const tpls of Object.values(BANK)) {
    let count = 0, guard = 0;
    while (count < perClass && guard++ < perClass * 40) {
      const text = fill(pick(rng, tpls), rng);
      if (seen.has(text)) continue;
      seen.add(text);
      rows.push({ text, label: teacher.label(text) });
      count++;
    }
  }
  return rows;
}

