"""Ed25519 (RFC 8032) на чистом Python: подпись, которую может проверить любой.

ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ
--------------------------
До него свидетельство о работе (`credential.py`) подписывалось HMAC-SHA256.
HMAC — симметричная схема: проверить подпись может только тот, у кого есть
секрет issuer, а кто может проверить — тот может и подделать. Переносимой
репутации при таком клейме не бывает: цеховое клеймо, которое проверяет только
сам мастер, клеймом не является.

Нужна асимметричная подпись, а в стандартной библиотеке Python её нет.
Выход — не зависимость, а арифметика: Ed25519 целиком описан в RFC 8032, и для
него достаточно `hashlib.sha512` и целых чисел. Ниже ровно это и сделано.

ЧТО ЗДЕСЬ ПРОИСХОДИТ (математика на уровне «зачем каждая строка»)
-----------------------------------------------------------------
Работаем на скрученной кривой Эдвардса edwards25519 над полем вычетов по
простому p = 2²⁵⁵ − 19:

    −x² + y² = 1 + d·x²·y²

Точки кривой складываются (есть формула сложения), значит есть и умножение
точки на целое число: k·B — это B, сложенная с собой k раз. Ключевое свойство,
на котором стоит вся схема: по k·B вычислить k нельзя (дискретный логарифм),
а проверить равенство точек — можно. Отсюда:

    секрет     a  — число (выводится хэшем из 32-байтового seed);
    публичный  A = a·B — точка, та же операция, но обратно не считается;
    подпись    (R, S), где R = r·B, а S связывает r, секрет a и хэш сообщения;
    проверка   [S]·B = R + [k]·A — равенство, в котором секрета a уже нет.

Поэтому проверяющему хватает A. В этом всё отличие от HMAC и весь смысл этапа.

Три технические детали, без которых реализация не сходится с эталоном, и ни
одна из них не является украшением:

  * Координаты расширенные (X : Y : Z : T), x = X/Z, y = Y/Z, x·y = T/Z.
    Так в формуле сложения нет делений — а деление по модулю (взятие обратного)
    стоит возведения в степень, то есть в 250 раз дороже умножения. Одно
    деление остаётся — на самом выходе, при сжатии точки в 32 байта.
  * Кодирование точки — little-endian `y`, а бит знака `x` кладётся в старший
    (255-й) бит. Поэтому публичный ключ и R занимают 32 байта, а не 64.
  * Секретный скаляр «подчищается» битами (clamping): младшие три бита
    гасятся, 254-й ставится. Это не суеверие: гашение младших битов убирает
    кофакторные утечки, а старший бит фиксирует длину скаляра, чтобы
    умножение не выдавало её временем работы.

ЧЕСТНЫЕ ОГРАНИЧЕНИЯ — ЧИТАТЬ ДО ПРИМЕНЕНИЯ
------------------------------------------
1. Реализация НЕ constant-time. Умножение точки идёт простым double-and-add с
   ветвлением по биту скаляра, а большие числа Python сами по себе работают
   за время, зависящее от значений. Значит, она уязвима к атакам по времени:
   противник, который может много раз мерить время подписи на той же машине,
   способен восстанавливать биты секрета. Для подписи ценных активов нужна
   libsodium или `cryptography` (там Ed25519 собран в C с защитой от этого);
   здесь их нет сознательно — весь проект работает без зависимостей.
2. Она медленная. Измерено на машине разработки (Python 3.11, CPython без JIT):
   порядка 200 подписей и 200 проверок в секунду, то есть около 5 мс на
   операцию. Подпись и проверка стоят одинаково не случайно: в обеих по два
   умножения точки на скаляр — подпись считает A = a·B и R = r·B, проверка
   считает [S]B и [k]A. C-реализация (libsodium) делает то же за единицы
   микросекунд, то есть здесь в сотни раз медленнее. Для пакетной обработки
   десятков тысяч подписей не годится; для выдачи и проверки свидетельств —
   с запасом: проверка портфолио из десяти писем занимает пятьдесят
   миллисекунд, и это заметно меньше одного HTTP-запроса к сервису.
3. Поведение на вырожденных кодировках (неканонические `y` ≥ p, точки малого
   порядка) соответствует референсу из приложения RFC 8032: проверяется
   уравнение `[S]B = R + [k]A` без умножения на кофактор. Разные библиотеки
   на таких входах расходятся между собой; на нормальных входах — нет, и
   именно это сверяется в тестах.
4. Для чего она здесь годится: проверяемая ПЕРЕНОСИМОСТЬ свидетельств в
   исследовательском стенде, где ключи не стоят денег. Свойство, которое она
   даёт, — третья сторона проверяет подпись, не имея никаких секретов, — и
   оно работает в полную силу. Свойство, которого она не даёт, — стойкость к
   атакам по сторонним каналам, — названо выше.

ПРОВЕРКА ПРОТИВ ВНЕШНЕГО ЭТАЛОНА
--------------------------------
Самосертификация здесь была бы особенно смешна: реализация, которая «подписала
и сама проверила», совместима ровно сама с собой. Поэтому `act/tests/test_ed25519.py`
сверяет её с двумя независимыми источниками: с официальными тест-векторами
RFC 8032 §7.1 (побайтово, включая пустое сообщение и сообщение на 1023 байта) и
с библиотекой `cryptography` — её `verify` обязана принимать наши подписи, а наш
`verify` — её. В РАНТАЙМЕ библиотеки нет: этот модуль импортирует ровно
`hashlib`, `secrets` и `base64` — и ничего больше, — а тест отдельно убеждается
в этом тремя способами: разбором `ast`, поиском по тексту кода и по `sys.modules`
свежего процесса, который рантайм импортировал.

ДЛЯ СПЕЦИФИКАЦИИ (готовый абзац, координатору — перенести)
----------------------------------------------------------
    Подпись свидетельства о работе ДОЛЖНА быть асимметричной: проверяющий
    НЕ ДОЛЖЕН нуждаться ни в каком секрете. Реализация уровня 4 использует
    Ed25519 (RFC 8032, PureEdDSA над edwards25519), приватный ключ — 32-байтовый
    seed, публичный — сжатая точка 32 байта, подпись — 64 байта. Симметричная
    подпись (HMAC) ДОПУСКАЕТСЯ только как унаследованная схема для ранее
    выданных свидетельств и НЕ СЧИТАЕТСЯ публично проверяемой.
"""

from __future__ import annotations

import base64
import hashlib
import secrets

__all__ = [
    "Ed25519Error", "keypair", "public_hex", "public_of", "sign", "verify",
    "SEED_SIZE", "PUBLIC_SIZE", "SIGNATURE_SIZE",
]

# ────────────────────────────────────────────────────────────────────────────
# Параметры кривой (RFC 8032 §5.1). Константы, а не магические числа в коде:
# каждое из них проверяемо по тексту RFC.
# ────────────────────────────────────────────────────────────────────────────

#: Модуль поля: 2²⁵⁵ − 19. Отсюда и название кривой.
P = 2 ** 255 - 19

#: Порядок подгруппы, в которой живут ключи. Скаляры подписи берутся по модулю
#: L, а не p: это разные числа, и путаница между ними — классическая ошибка.
L = 2 ** 252 + 27742317777372353535851937790883648493

#: Коэффициент кривой d = −121665/121666 (mod p).
D = -121665 * pow(121666, P - 2, P) % P

#: Квадратный корень из −1 в поле. Нужен при восстановлении x по y: формула
#: даёт корень с точностью до множителя √−1, и его приходится подбирать.
_SQRT_M1 = pow(2, (P - 1) // 4, P)

SEED_SIZE = 32
PUBLIC_SIZE = 32
SIGNATURE_SIZE = 64

#: Нейтральный элемент (точка «ноль») в расширенных координатах: x=0, y=1.
_ZERO = (0, 1, 1, 0)


class Ed25519Error(ValueError):
    """Ключ или подпись не той формы: длина, кодировка, нечисловые символы."""


# ────────────────────────────────────────────────────────────────────────────
# Арифметика точек
# ────────────────────────────────────────────────────────────────────────────


def _inv(x: int) -> int:
    """Обратное по модулю p через малую теорему Ферма.

    `pow` с тремя аргументами уходит в C, поэтому это самая быстрая доступная
    форма деления в поле. И единственное место, где мы вообще делим, — всё
    остальное живёт в расширенных координатах именно чтобы делений не было.
    """
    return pow(x, P - 2, P)


def _add(p1: tuple[int, int, int, int],
         p2: tuple[int, int, int, int]) -> tuple[int, int, int, int]:
    """Сложение точек в расширенных координатах (RFC 8032 §5.1.4).

    Формула «унифицированная»: она верна и когда слагаемые разные, и когда
    это одна и та же точка. Поэтому отдельного удвоения нет — меньше кода,
    меньше мест, где можно разойтись с эталоном.
    """
    x1, y1, z1, t1 = p1
    x2, y2, z2, t2 = p2
    a = (y1 - x1) * (y2 - x2) % P
    b = (y1 + x1) * (y2 + x2) % P
    c = 2 * t1 * t2 * D % P
    d = 2 * z1 * z2 % P
    e, f, g, h = b - a, d - c, d + c, b + a
    return (e * f % P, g * h % P, f * g % P, e * h % P)


def _mul(scalar: int, point: tuple[int, int, int, int]) -> tuple[int, int, int, int]:
    """Умножение точки на скаляр: double-and-add по битам справа налево.

    Здесь и живёт отмеченное в заголовке ограничение: ветка `if bit` выполняется
    только для единичных битов секрета, и время работы зависит от их числа.
    Constant-time реализация выбирала бы слагаемое без ветвления.
    """
    result = _ZERO
    while scalar > 0:
        if scalar & 1:
            result = _add(result, point)
        point = _add(point, point)
        scalar >>= 1
    return result


def _equal(p1: tuple[int, int, int, int], p2: tuple[int, int, int, int]) -> bool:
    """Равны ли точки. Сравнение «на кресте», потому что Z у них разные.

    (X₁/Z₁ = X₂/Z₂) проверяется как X₁·Z₂ = X₂·Z₁ — снова чтобы не делить.
    """
    x1, y1, z1, _ = p1
    x2, y2, z2, _ = p2
    return (x1 * z2 - x2 * z1) % P == 0 and (y1 * z2 - y2 * z1) % P == 0


def _recover_x(y: int, sign_bit: int) -> int | None:
    """Восстановить x по y и одному биту знака. None — такой точки на кривой нет.

    Из уравнения кривой x² = (y² − 1)/(d·y² + 1). Квадратный корень в этом поле
    берётся возведением в степень (p+3)/8, но даёт ответ с точностью до
    множителя √−1 — поэтому второй кандидат проверяется явно, и если не подошёл
    ни один, значит переданные 32 байта просто не кодируют точку кривой.
    """
    if y >= P:
        return None
    x2 = (y * y - 1) * _inv(D * y * y + 1) % P
    if x2 == 0:
        # Единственная точка с x = 0: знак «минус нуля» не существует.
        return None if sign_bit else 0
    x = pow(x2, (P + 3) // 8, P)
    if x * x % P != x2:
        x = x * _SQRT_M1 % P
    if x * x % P != x2:
        return None
    if x & 1 != sign_bit:
        x = P - x
    return x


#: Базовая точка B: y = 4/5, x — положительный корень (RFC 8032 §5.1).
_B_Y = 4 * _inv(5) % P
_B_X = _recover_x(_B_Y, 0)
assert _B_X is not None  # иначе ошибка в _recover_x, и проверять нечего
B = (_B_X, _B_Y, 1, _B_X * _B_Y % P)


def _compress(point: tuple[int, int, int, int]) -> bytes:
    """Точка → 32 байта: little-endian y, младший бит x в старшем бите."""
    x, y, z, _ = point
    zi = _inv(z)
    x, y = x * zi % P, y * zi % P
    return int.to_bytes(y | ((x & 1) << 255), 32, "little")


def _decompress(data: bytes) -> tuple[int, int, int, int] | None:
    """32 байта → точка, или None, если они точку не кодируют."""
    if len(data) != 32:
        return None
    y = int.from_bytes(data, "little")
    sign_bit = y >> 255
    y &= (1 << 255) - 1
    x = _recover_x(y, sign_bit)
    if x is None:
        return None
    return (x, y, 1, x * y % P)


# ────────────────────────────────────────────────────────────────────────────
# Приведение ключей: байты, hex или base64 — на входе всё, внутри байты
# ────────────────────────────────────────────────────────────────────────────


def _unhex(text: str) -> bytes | None:
    try:
        return bytes.fromhex(text)
    except ValueError:
        return None


def _unb64(text: str) -> bytes | None:
    try:
        return base64.b64decode(text, validate=True)
    except Exception:
        return None


def _material(value: bytes | bytearray | str, size: int, what: str) -> bytes:
    """Привести ключ/подпись к `size` байтам.

    Принимаются байты, hex и base64 — потому что свидетельство ездит в JSON,
    где байтов нет, а разные стенды хранят ключи по-разному. Кодировка
    определяется по форме, а не по флагу: hex длиной ровно 2·size однозначен,
    и только если это не он, пробуется base64.
    """
    if isinstance(value, (bytes, bytearray)):
        raw: bytes | None = bytes(value)
    elif isinstance(value, str):
        text = value.strip()
        raw = _unhex(text) if len(text) == 2 * size else None
        if raw is None:
            raw = _unb64(text)
    else:
        raise Ed25519Error(f"{what}: ожидались байты или строка, получено {type(value).__name__}")
    if raw is None:
        raise Ed25519Error(f"{what}: строка не является ни hex, ни base64")
    if len(raw) != size:
        raise Ed25519Error(f"{what}: нужно {size} байт, получено {len(raw)}")
    return raw


def _message(value: bytes | bytearray | str) -> bytes:
    """Сообщение: строка подписывается как UTF-8, и это объявлено, а не угадано."""
    if isinstance(value, (bytes, bytearray)):
        return bytes(value)
    if isinstance(value, str):
        return value.encode("utf-8")
    raise Ed25519Error(f"сообщение: ожидались байты или строка, получено {type(value).__name__}")


# ────────────────────────────────────────────────────────────────────────────
# Схема подписи (RFC 8032 §5.1.5–§5.1.7)
# ────────────────────────────────────────────────────────────────────────────


def _expand(seed: bytes) -> tuple[int, bytes]:
    """seed → (секретный скаляр a, префикс для детерминированного r).

    Из одного хэша SHA-512 получаются две независимые половины: первая даёт
    скаляр a (после подчистки битов), вторая — «соль» подписи. Вторая половина
    нужна, чтобы r считался детерминированно из сообщения, а не брался из
    генератора случайных чисел: повторно использованный r в этой схеме
    раскрывает секрет целиком, и RFC убирает эту возможность вовсе.
    """
    h = hashlib.sha512(seed).digest()
    a = int.from_bytes(h[:32], "little")
    a &= (1 << 254) - 8   # погасить три младших бита
    a |= 1 << 254         # поставить 254-й
    return a, h[32:]


def _hash_mod_l(*chunks: bytes) -> int:
    return int.from_bytes(hashlib.sha512(b"".join(chunks)).digest(), "little") % L


def keypair(seed: bytes | bytearray | str | None = None) -> tuple[str, str]:
    """Пара ключей: (приватный, публичный), оба — hex из 32 байт.

    `seed` — те самые 32 байта, которые RFC 8032 называет приватным ключом.
    Без аргумента берутся из `secrets.token_bytes`: это CSPRNG операционной
    системы, единственный пригодный источник для ключа.

    Возвращается hex, а не байты, потому что ключи здесь живут в JSON
    (свидетельство, паспорт) и в человекочитаемых файлах стенда. Байты на
    входе любых функций модуля тоже принимаются.
    """
    raw = secrets.token_bytes(SEED_SIZE) if seed is None else _material(seed, SEED_SIZE, "seed")
    a, _ = _expand(raw)
    return raw.hex(), _compress(_mul(a, B)).hex()


def public_hex(public: bytes | bytearray | str) -> str:
    """Привести публичный ключ к одной форме — hex из 32 байт.

    Нужно, чтобы сравнение «ключ из паспорта против ключа из письма» не
    оказалось сравнением кодировок: одни и те же 32 байта в hex и в base64 —
    разные строки, и наивное `==` отвергло бы верный ключ.
    """
    return _material(public, PUBLIC_SIZE, "публичный ключ").hex()


def public_of(private: bytes | bytearray | str) -> str:
    """Публичный ключ по приватному: A = a·B.

    Отдельной функцией — чтобы паспорт можно было восстановить из сохранённого
    seed, не храня публичный ключ второй копией, которая может разойтись.
    """
    a, _ = _expand(_material(private, SEED_SIZE, "приватный ключ"))
    return _compress(_mul(a, B)).hex()


def sign(message: bytes | bytearray | str, private: bytes | bytearray | str) -> bytes:
    """Подписать сообщение. Возвращает ровно 64 байта: R (32) ‖ S (32).

    Подпись детерминирована: одно и то же сообщение тем же ключом даёт тот же
    результат. Это свойство RFC, а не упрощение, и оно удобно в стенде —
    повторная выдача свидетельства не меняет подпись, значит расхождение
    подписей всегда означает расхождение содержимого.
    """
    msg = _message(message)
    a, prefix = _expand(_material(private, SEED_SIZE, "приватный ключ"))
    pub = _compress(_mul(a, B))

    r = _hash_mod_l(prefix, msg)
    big_r = _compress(_mul(r, B))
    k = _hash_mod_l(big_r, pub, msg)
    s = (r + k * a) % L
    return big_r + int.to_bytes(s, 32, "little")


def verify(message: bytes | bytearray | str,
           signature: bytes | bytearray | str,
           public: bytes | bytearray | str) -> bool:
    """Проверить подпись публичным ключом. Никаких секретов не требуется.

    Возвращает False, а не исключение, на любом непригодном входе — неверная
    длина, не точка кривой, S вне диапазона. Так сделано потому, что на вход
    `verify` по определению приходят данные от того, кто мог их подделать:
    заставлять каждого вызывающего оборачивать проверку в try — верный способ
    получить код, который считает исключение «ещё не проверено».

    S ≥ L отвергается явно: иначе к подписи можно было бы прибавить L и
    получить вторую, тоже проходящую проверку (signature malleability), а
    свидетельство с двумя разными действительными подписями — приглашение к
    спору о том, какая из них «та самая».
    """
    try:
        sig = _material(signature, SIGNATURE_SIZE, "подпись")
        pub = _material(public, PUBLIC_SIZE, "публичный ключ")
    except Ed25519Error:
        return False

    point_a = _decompress(pub)
    if point_a is None:
        return False
    point_r = _decompress(sig[:32])
    if point_r is None:
        return False
    s = int.from_bytes(sig[32:], "little")
    if s >= L:
        return False

    msg = _message(message)
    k = _hash_mod_l(sig[:32], pub, msg)
    # Уравнение проверки: [S]B = R + [k]A. Секрета a в нём нет — в этом и
    # состоит всё отличие асимметричной схемы от HMAC.
    return _equal(_mul(s, B), _add(point_r, _mul(k, point_a)))
