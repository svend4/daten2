"""Криптография, которой нет в стандартной библиотеке Python.

Пакет существует по одной причине: протоколу нужна АСИММЕТРИЧНАЯ подпись, а в
stdlib есть только `hmac` и `hashlib` — то есть симметричные схемы. Симметричной
подписью переносимое свидетельство не подписать: проверить её может лишь тот, у
кого есть секрет issuer, а кто может проверить, тот может и подделать.

Правило проекта «только стандартная библиотека» при этом не нарушено и не
обойдено: Ed25519 (RFC 8032) не требует ничего, кроме SHA-512 и целых чисел, и
реализован здесь полностью — `ed25519.py` импортирует ровно `hashlib`, `secrets`
и `base64`. Зависимость заменена арифметикой, а не спрятана.

Что это стоит и чего не даёт — честно написано в заголовке `ed25519.py`
(не constant-time; около 5 мс на операцию). Читать до применения.
"""

