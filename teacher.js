// teacher.js — детерминированный «учитель»: правила классификации намерения
// покупателя (те же, что в детерминированной витрине). Он размечает данные для
// обучения ученика. Классы намерений — целевые метки дистилляции.
const LABELS = ['greet', 'checkout', 'cart', 'add', 'filter', 'catalog', 'unknown'];

function label(text) {
  const t = String(text || '').toLowerCase();
  if (/привет|здравств|добр(ый|ое|ый день)|начн|помог|что посовет|подскаж/.test(t)) return 'greet';
  if (/оформ|оплат|checkout|заверш(и|ить)|купить\s+всё|готов.*заказ|сделать заказ/.test(t)) return 'checkout';
  if (/корзин/.test(t) && !/добав|положи/.test(t)) return 'cart';
  if (/добав|хочу|куп(и|ить|лю)|возьм|беру|бер[её]м|положи|в корзину|закаж/.test(t)) return 'add';
  if (/дешёв|дешев|недорог|бюджет|до\s*\d|рекоменд|популярн|ярк|красн|жёлт|желт|ароматн|пахн|нежн/.test(t)) return 'filter';
  if (/каталог|ассортимент|покажи|что есть|что у вас|витрин|список товар|выбор|цвет(ы|ов)/.test(t)) return 'catalog';
  return 'unknown';
}

module.exports = { label, LABELS };
